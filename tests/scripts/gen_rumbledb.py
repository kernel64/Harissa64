#!/usr/bin/env python3
"""Generates core/cart/h64_rumbledb.inc: the cartridges that support the
Rumble Pak (header CRC1, CRC2), from mupen64plus's ROM catalogue ("Rumble=Yes";
the copy V1 shipped as files/mupen64plus.ini, GPL v2, see THIRD_PARTY.md).
Entries with RefMD5 inherit from the entry they name. The save types stay in
h64_savedb.inc (tests/scripts/gen_savedb.py), untouched by this table.

Run (from the repository root): python tests/scripts/gen_rumbledb.py
With --codes [ROM folder] (after building build-msvc with the new table), it
also writes core/cart/h64_rumbledb_codes.inc: the game codes (region letter
left out) whose ROMs in the folder all support the Rumble Pak, for ROM hacks
the CRC table does not know (Smash Remix keeps Smash's code).
"""
import os
import re
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
# V1's copy of the catalogue: master lost it when V2 was merged (e763859).
SOURCE = "e763859^:files/mupen64plus.ini"


def main():
    text = subprocess.run(["git", "show", SOURCE], cwd=ROOT, capture_output=True, text=True, encoding="latin-1").stdout
    if not text:
        raise SystemExit("cannot read " + SOURCE)
    entries, cur = {}, None
    for line in text.splitlines():
        line = line.strip()
        if line.startswith("[") and line.endswith("]"):
            cur = entries.setdefault(line[1:-1], {})
        elif cur is not None and "=" in line and not line.startswith(";"):
            k, v = line.split("=", 1)
            cur[k.strip()] = v.strip()

    def get(e, key, depth=0):
        if key in e or depth > 4:
            return e.get(key)
        ref = e.get("RefMD5")
        return get(entries[ref], key, depth + 1) if ref in entries else None

    rows, catalogue = {}, {}
    for e in entries.values():
        crc = e.get("CRC")
        if not crc:
            continue
        c1, c2 = (int(x, 16) for x in crc.split())
        yes = get(e, "Rumble") == "Yes"
        catalogue[(c1, c2)] = catalogue.get((c1, c2), False) or yes
        if yes:
            rows[(c1, c2)] = get(e, "GoodName") or ""
    out = ["// Generated by tests/scripts/gen_rumbledb.py from mupen64plus's ROM catalogue: do not edit.",
           "// { header CRC1, header CRC2 } of the cartridges that support the Rumble Pak, sorted."]
    for (c1, c2), name in sorted(rows.items()):
        out.append("{ 0x%08Xu, 0x%08Xu },   // %s" % (c1, c2, name.replace("*/", "")[:60]))
    path = os.path.join(ROOT, "core", "cart", "h64_rumbledb.inc")
    open(path, "w", newline="\n", encoding="ascii", errors="replace").write("\n".join(out) + "\n")
    print("wrote %s (%d entries)" % (path, len(rows)))
    if "--codes" in sys.argv:
        rest = sys.argv[sys.argv.index("--codes") + 1:]
        write_codes(rest[0] if rest else os.path.join(ROOT, "xbox64", "Release", "roms"), catalogue)


def write_codes(folder, catalogue):
    h64test = os.path.join(ROOT, "build-msvc", "h64test.exe")
    codes = {}
    for name in sorted(os.listdir(folder)):
        if not name.lower().endswith((".z64", ".n64", ".v64", ".zip")):
            continue
        out = subprocess.run([h64test, "--rom", os.path.join(folder, name), "--info"], capture_output=True, text=True,
                             errors="replace").stdout
        m = re.search(r'^\[rom\] "[^"]*" (\w{4}) ', out, re.M)
        c = re.search(r'^\[info\] header CRCs: ([0-9A-F]{8}) ([0-9A-F]{8})$', out, re.M)
        if not m or not c or not m.group(1).isalnum():
            continue
        key = (int(c.group(1), 16), int(c.group(2), 16))
        if key not in catalogue:
            continue   # a ROM hack or an unknown dump: says nothing about its code
        codes.setdefault(m.group(1)[:3], []).append((catalogue[key], name))
    out = ["// Generated by tests/scripts/gen_rumbledb.py --codes from a ROM folder: do not edit.",
           "// { game code without the region letter }: Rumble Pak support of ROM hacks the CRC table does not know."]
    n = 0
    for code in sorted(codes):
        if all(y for y, _ in codes[code]):
            out.append('{ "%s" },   // %s' % (code, codes[code][0][1]))
            n += 1
    if not n:
        out.append('{ "" },')
    path = os.path.join(ROOT, "core", "cart", "h64_rumbledb_codes.inc")
    open(path, "w", newline="\n").write("\n".join(out) + "\n")
    print("wrote %s (%d codes)" % (path, n))


if __name__ == "__main__":
    main()
