#!/usr/bin/env python3
"""Generates core/cart/h64_savedb_codes.inc: the save type of each game code
(header 0x3B..0x3E, e.g. "NB7E"), for cartridges the CRC table
(h64_savedb.inc) does not know. ROM hacks keep the game's code but change its
CRCs: Banjo-Tooie hacks got the default save (EEPROM 4 Kbit and a Controller
Pak) and stopped on "NO CONTROLLER" instead of the game's EEPROM 16 Kbit.

The table is made from the ROMs of a folder with h64test --info (the CRC table
gives each known ROM's type); a code goes in only when all its ROMs agree.

Run (from the repository root, after building build-msvc):
  python tests/scripts/gen_savedb_codes.py [ROM folder]
"""
import os
import re
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
H64TEST = os.path.join(ROOT, "build-msvc", "h64test.exe")
NAMES = {"none": "H64_SAVE_NONE", "EEPROM 4 Kbit": "H64_SAVE_EEPROM_4K", "EEPROM 16 Kbit": "H64_SAVE_EEPROM_16K",
         "SRAM": "H64_SAVE_SRAM", "FlashRAM": "H64_SAVE_FLASH"}


def main():
    folder = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "xbox64", "Release", "roms")
    codes = {}
    for name in sorted(os.listdir(folder)):
        if not name.lower().endswith((".z64", ".n64", ".v64", ".zip")):
            continue
        out = subprocess.run([H64TEST, "--rom", os.path.join(folder, name), "--info"], capture_output=True, text=True,
                             errors="replace").stdout
        m = re.search(r'^\[rom\] "[^"]*" (\w{4}) ', out, re.M)
        s = re.search(r'^\[save\] save type: (.+?)(, Controller Pak)?$', out, re.M)
        if not m or not s or s.group(1) not in NAMES or not m.group(1).isalnum():
            continue
        codes.setdefault(m.group(1), set()).add((NAMES[s.group(1)], 1 if s.group(2) else 0, name))
    lines = ["// Generated by tests/scripts/gen_savedb_codes.py from a ROM folder: do not edit.",
             "// { game code, save type, Controller Pak }: used when the CRC table does not know the cartridge."]
    for code in sorted(codes):
        kinds = set((t, p) for t, p, _ in codes[code])
        if len(kinds) != 1:
            continue   # the ROMs of this code disagree: left to the default
        t, p = kinds.pop()
        lines.append('{ "%s", %s, %d },   // %s' % (code, t, p, sorted(codes[code])[0][2]))
    path = os.path.join(ROOT, "core", "cart", "h64_savedb_codes.inc")
    open(path, "w", newline="\n").write("\n".join(lines) + "\n")
    print("%d codes -> %s" % (len(lines) - 2, path))


if __name__ == "__main__":
    main()
