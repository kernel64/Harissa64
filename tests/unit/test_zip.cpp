void test_zip(H64TestContext *ctx)
{
    static u8 rom[8192];
    H64ZipMem m;
    H64ZipReader r;
    H64ZipEntry e;
    u8 head[64];
    u32 i, bad = 0;
    m.data = s_zip;
    m.size = sizeof(s_zip);
    r.user = &m;
    r.size = m.size;
    r.read = h64_zip_mem_read;
    H64_CHECK_EQ(ctx, h64_zip_find_rom(&r, &e), 0);
    H64_CHECK(ctx, !strcmp(e.name, "Game (U).z64"));
    H64_CHECK_EQ(ctx, e.method, 8);
    H64_CHECK_EQ(ctx, e.size, 8192);
    H64_CHECK_EQ(ctx, h64_zip_extract(&r, &e, head, sizeof(head)), 0);   // the start only
    H64_CHECK_EQ(ctx, head[0], 0x80);
    H64_CHECK_EQ(ctx, head[40], (40 * 7) & 0xFF);
    H64_CHECK_EQ(ctx, h64_zip_extract(&r, &e, rom, sizeof(rom)), 0);     // whole, CRC checked
    for (i = 4; i < 8192; i++)
        if (rom[i] != ((i * 7 + (i >> 8)) & 0xFF)) bad++;
    H64_CHECK_EQ(ctx, bad, 0);
    e.crc ^= 1;
    H64_CHECK_EQ(ctx, h64_zip_extract(&r, &e, rom, sizeof(rom)), -1);    // bad CRC
    r.size = 100;                                                          // truncated: no end record
    H64_CHECK_EQ(ctx, h64_zip_find_rom(&r, &e), -1);
}
